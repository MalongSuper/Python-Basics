# Mathematical Operations
import numpy as np

# Constants
print(np.pi)
print(np.e)

# Sum, Mean and Median
data = np.array([10, 20, 30, 40, 50])

print(np.sum(data))
print(np.mean(data))
print(np.median(data))

# Minimum and Maximum
print(np.min(data))
print(np.max(data))

# Variance and Standard Deviation
print(np.var(data))
print(np.std(data))

# Square Root and Absolute Value
print(np.sqrt(16))
print(np.abs(-25))

# Power and Exponential
print(np.power(2, 5))
print(np.exp(1))

# Logarithms
print(np.log(10))
print(np.log2(8))
print(np.log10(100))
